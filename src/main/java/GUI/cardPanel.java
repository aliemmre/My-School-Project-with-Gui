    private void jButtonSignInPlay1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSignInPlay1ActionPerformed

        String nickname = jTextFieldSignInNickname.getText().trim();
        String password = jPasswordFieldSıgnIn.getText().trim();

        int result = -1;
        try {
            result = registerAndSign.signIn(nickname, password);
        } catch (IOException ex) {
            System.out.println(ex.toString());
        }

        if (result == 0) {
            adminPlayer = new Admin();

            new AdminFrame().setVisible(true);

            JOptionPane.showMessageDialog(this, adminPlayer.displayWhichPlayer());

            SwingUtilities.getWindowAncestor(this).dispose();
        } else if (result == 1) {
            try {
                normalPlayer = new NormalPlayer(
                        nickname,
                        ReaderAndWriterFileProcess.getterLastIdFromFile(nickname),
                        new TakeLetter(),
                        new Estimate()
                );
            } catch (IOException ex) {
                System.out.println(ex.toString());

            }

            JOptionPane.showMessageDialog(this, "Game Started!! \n"+normalPlayer.displayWhichPlayer());

            try {
                new GameFrame(normalPlayer).setVisible(true);
                SwingUtilities.getWindowAncestor(this).dispose();

            } catch (IOException ex) {
                java.util.logging.Logger.getLogger(cardPanel.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
            }
        } else { // Hatalı giriş
            JOptionPane.showMessageDialog(this, "Kullanıcı adı veya şifre hatalı!");

            jTextFieldSignInNickname.setText("");
            jPasswordFieldSıgnIn.setText("");
        }

    }//GEN-LAST:event_jButtonSignInPlay1ActionPerformed

