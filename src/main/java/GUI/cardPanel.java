    private void jButtonRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRegisterActionPerformed

        String nickname = jTextFieldRegisterNickname.getText().trim();
        String password1 = jPasswordFieldRegister.getText().trim();
        String password2 = jPasswordFieldRegisterCheck.getText().trim();

        if (nickname.isEmpty() || password1.isEmpty() || password2.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter valid nickname and password!",
                    "Giriş Hatası",
                    JOptionPane.ERROR_MESSAGE);
            return; // Kodun geri kalanını çalıştırmadan metoddan çık
        }
        try {
            if (registerAndSign.register(nickname, password1, password2)) {

                JOptionPane.showMessageDialog(this, "Kayıt başarılı!");
                jTextFieldRegisterNickname.setText("");
                jPasswordFieldRegister.setText("");
                jPasswordFieldRegisterCheck.setText("");
                showSignIn();
            } else {
                JOptionPane.showMessageDialog(this, "Kayıt başarısız!");
                jTextFieldRegisterNickname.setText("");
                jPasswordFieldRegister.setText("");
                jPasswordFieldRegisterCheck.setText("");
            }
        } catch (IOException ex) {
            java.util.logging.Logger.getLogger(cardPanel.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);

        }

    }//GEN-LAST:event_jButtonRegisterActionPerformed

